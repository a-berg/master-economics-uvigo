import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {FileBlob,SpreadsheetFile} from '@oai/artifact-tool';
await fs.mkdir('tmp/ipc',{recursive:true});
const input='output/ipc/IPC-ADRIAN BERGES-revisado.xlsx';
const hash=createHash('sha256').update(await fs.readFile(input)).digest('hex');
const data=JSON.parse(await fs.readFile('entregas/ipc/ponderaciones_2025.json','utf8'));
const w=await SpreadsheetFile.importXlsx(await FileBlob.load(input));
const s=w.worksheets.getItem('Tablas e Gráficos');
const preview=async suffix=>{
 const blob=await w.render({sheetName:s.name,range:'A15:D32',scale:1.5,format:'png'});
 await fs.writeFile(`tmp/ipc/ponderaciones_${suffix}.png`,new Uint8Array(await blob.arrayBuffer()));
};
await preview('antes_2025');
if(!process.argv.includes('--edit')) process.exit(0);
await fs.copyFile(input,`tmp/ipc/antes_ponderaciones_${hash.slice(0,12)}.xlsx`);
const previous=s.getRange('E2:G5').values;
s.getRange('C16').values=[['Referencia oficial: 2025']];
s.getRange('C18:D29').values=data.spain.map((v,i)=>[v,data.galicia[i]]);
w.recalculate();
assert.deepEqual(s.getRange('E2:G5').values,previous,'El IPC personal no debe variar');
assert.ok(Math.abs(s.getRange('C30').values[0][0]-100.0001)<1e-8);
assert.ok(Math.abs(s.getRange('D30').values[0][0]-100)<1e-8);
console.log((await w.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!',options:{useRegex:true,maxResults:10},maxChars:1200})).ndjson);
await preview('2025');
await(await SpreadsheetFile.exportXlsx(w)).save('tmp/ipc/ponderaciones_2025.xlsx');
await fs.writeFile('tmp/ipc/ponderaciones_entrada.sha256',hash+'\n');
console.log('Actualizadas 24 ponderaciones y la etiqueta de referencia; IPC personal conservado.');
